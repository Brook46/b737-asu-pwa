#!/usr/bin/env python3
"""Build flight-card-pwa/modules/mapdata.js — country borders and FIR lines
for the Route info map, embedded (the map must work with no network).

Usage: python3 scripts/build-mapdata.py <ne_50m_admin_0_boundary_lines_land.geojson> <Boundaries.geojson>

Sources:
  Country borders — Natural Earth 1:50m admin-0 boundary lines (land),
    public domain: https://github.com/nvkelso/natural-earth-vector
  FIRs — VATSIM VAT-Spy data project Boundaries.geojson, CC BY-SA 4.0:
    https://github.com/vatsimnetwork/vatspy-data-project
    (a flight-sim community's tracing of the real FIRs: rough, for orientation
    only). Only plain four-letter ids are kept — the set also carries
    simulator sectors (LCCC-E, …) and groupings that aren't real FIRs.

Same storage as worldmap.js: each line quantised to 1/100 degree and
delta-encoded [lon0, lat0, dLon, dLat, ...], after Douglas-Peucker.
"""
import json, os, re, sys

TOL_BORDER = 0.04
TOL_FIR = 0.06

def dp(pts, tol):
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        ax, ay = pts[a]; bx, by = pts[b]
        dx, dy = bx - ax, by - ay
        L = (dx * dx + dy * dy) ** 0.5
        best, idx = 0.0, -1
        for i in range(a + 1, b):
            px, py = pts[i]
            d = abs(dy * px - dx * py + bx * ay - by * ax) / L if L else ((px - ax) ** 2 + (py - ay) ** 2) ** 0.5
            if d > best:
                best, idx = d, i
        if best > tol and idx > 0:
            keep[idx] = True
            stack += [(a, idx), (idx, b)]
    return [p for p, k in zip(pts, keep) if k]

def pack(pts):
    q = [(round(x * 100), round(y * 100)) for x, y in pts]
    out = [q[0][0], q[0][1]]
    for (x0, y0), (x1, y1) in zip(q, q[1:]):
        if (x1, y1) == (x0, y0):
            continue
        out += [x1 - x0, y1 - y0]
    return out

def lines_of(geom):
    t, c = geom['type'], geom['coordinates']
    if t == 'LineString': return [c]
    if t == 'MultiLineString': return c
    if t == 'Polygon': return c
    if t == 'MultiPolygon': return [r for poly in c for r in poly]
    return []

borders = []
for f in json.load(open(sys.argv[1]))['features']:
    for line in lines_of(f['geometry']):
        s = dp([tuple(p[:2]) for p in line], TOL_BORDER)
        if len(s) >= 2:
            borders.append(pack(s))

firs, labels, seen = [], [], set()
for f in json.load(open(sys.argv[2]))['features']:
    p = f.get('properties') or {}
    fid = str(p.get('id') or '')
    if not re.fullmatch(r'[A-Z]{4}', fid):
        continue
    for ring in lines_of(f['geometry']):
        s = dp([tuple(pt[:2]) for pt in ring], TOL_FIR)
        if len(s) >= 4:
            firs.append(pack(s))
    if fid not in seen:
        try:
            labels.append([fid, round(float(p['label_lon']), 2), round(float(p['label_lat']), 2)])
            seen.add(fid)
        except (KeyError, TypeError, ValueError):
            pass

out = os.path.join(os.path.dirname(__file__), '..', 'flight-card-pwa', 'modules', 'mapdata.js')
J = lambda v: json.dumps(v, separators=(',', ':'))
with open(out, 'w', encoding='utf-8') as fh:
    fh.write(f"""// mapdata.js — country borders and FIR boundaries for the Route info map.
// GENERATED by scripts/build-mapdata.py — don't edit by hand.
//
// Borders: Natural Earth 1:50m admin-0 boundary lines (public domain).
// FIRs: VATSIM VAT-Spy data project (CC BY-SA 4.0) — a flight-sim community's
// tracing of the real FIRs: rough, for orientation only, never for navigation.
//
// Embedded like worldmap.js: the map is used in the air, offline. Lines are
// quantised to 1/100 degree and delta-encoded [lon0, lat0, dLon, dLat, ...].
const BORDERS = {J(borders)};
const FIRS = {J(firs)};
// [id, labelLon, labelLat]
export const FIR_LABELS = {J(labels)};

function decode(p) {{
  const out = new Array(p.length);
  let x = p[0], y = p[1];
  out[0] = x / 100; out[1] = y / 100;
  for (let k = 2; k < p.length; k += 2) {{ x += p[k]; y += p[k + 1]; out[k] = x / 100; out[k + 1] = y / 100; }}
  return out;
}}
function box(p) {{
  let x = p[0], y = p[1], a = x, b = x, c = y, d = y;
  for (let k = 2; k < p.length; k += 2) {{ x += p[k]; y += p[k + 1]; if (x < a) a = x; if (x > b) b = x; if (y < c) c = y; if (y > d) d = y; }}
  return [a / 100, c / 100, b / 100, d / 100];
}}
const BOX_B = BORDERS.map(box), BOX_F = FIRS.map(box);

function paths(set, boxes, proj, view, close) {{
  const out = [];
  const l = view.cLon - view.spanLon / 2, r = view.cLon + view.spanLon / 2;
  const b = view.cLat - view.spanLat / 2, t = view.cLat + view.spanLat / 2;
  for (let i = 0; i < set.length; i++) {{
    const [minLon, minLat, maxLon, maxLat] = boxes[i];
    if (maxLon < l || minLon > r || maxLat < b || minLat > t) continue;
    const pts = decode(set[i]);
    let d = '';
    for (let k = 0; k < pts.length; k += 2) d += (k ? 'L' : 'M') + proj.x(pts[k]).toFixed(1) + ',' + proj.y(pts[k + 1]).toFixed(1);
    out.push(close ? d + 'Z' : d);
  }}
  return out;
}}
export function borderPaths(proj, view) {{ return paths(BORDERS, BOX_B, proj, view, false); }}
export function firPaths(proj, view) {{ return paths(FIRS, BOX_F, proj, view, true); }}
""")
print(f'{len(borders)} border lines, {len(firs)} FIR rings, {len(labels)} labels, {os.path.getsize(out) // 1024} KB -> {out}')
