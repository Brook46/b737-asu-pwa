#!/usr/bin/env python3
"""Generates lib/core/src/display/fonts.cpp: 1-bit bitmap fonts for the
400x240 Sharp Memory display (and the browser simulator), rendered from
DejaVu Sans (Bitstream Vera licence: free to embed and redistribute).

    python3 tools/fontgen/fontgen.py   # needs Pillow and the DejaVu TTFs

Characters 32..126 plus 127 = degree sign. Threshold 50 % → crisp pixels.
"""
import os
from PIL import Image, ImageDraw, ImageFont

FONTS = [  # (C name, ttf, pixel size)
    ("kFontTiny", "DejaVuSans.ttf", 11),
    ("kFontSmall", "DejaVuSans.ttf", 14),
    ("kFontMedium", "DejaVuSans-Bold.ttf", 20),
    ("kFontLarge", "DejaVuSans-Bold.ttf", 34),
    ("kFontHuge", "DejaVuSans-Bold.ttf", 64),
]
TTF_DIR = "/usr/share/fonts/truetype/dejavu"
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "lib", "core", "src", "display", "fonts.cpp")


def glyph(font, ch):
    l, t, r, b = font.getbbox(ch)
    adv = int(round(font.getlength(ch)))
    w, h = max(r - l, 0), max(b - t, 0)
    if w == 0 or h == 0:
        return dict(w=0, h=0, xo=0, yo=0, adv=adv, rows=[])
    img = Image.new("L", (w, h), 0)
    ImageDraw.Draw(img).text((-l, -t), ch, font=font, fill=255)
    rows = []
    for y in range(h):
        row = bytearray((w + 7) // 8)
        for x in range(w):
            if img.getpixel((x, y)) >= 128:
                row[x // 8] |= 0x80 >> (x % 8)
        rows.append(bytes(row))
    return dict(w=w, h=h, xo=l, yo=t, adv=adv, rows=rows)


def main():
    out = ["// Generated by tools/fontgen/fontgen.py from DejaVu Sans. Do not edit.",
           "#include \"fonts.h\"", "", "namespace pg::gfx {", ""]
    for name, ttf, size in FONTS:
        font = ImageFont.truetype(os.path.join(TTF_DIR, ttf), size)
        ascent, descent = font.getmetrics()
        chars = [chr(c) for c in range(32, 127)] + ["°"]
        bits, gl = bytearray(), []
        for ch in chars:
            g = glyph(font, ch)
            gl.append((len(bits), g))
            for r in g["rows"]:
                bits += r
        out.append(f"static const uint8_t {name}Bits[] = {{")
        for i in range(0, len(bits), 24):
            out.append("  " + ", ".join(f"0x{b:02x}" for b in bits[i:i + 24]) + ",")
        out.append("};")
        out.append(f"static const Glyph {name}Glyphs[] = {{")
        for off, g in gl:
            out.append(f"  {{{off}, {g['w']}, {g['h']}, {g['xo']}, {g['yo']}, {g['adv']}}},")
        out.append("};")
        out.append(f"const Font {name} = {{{name}Bits, {name}Glyphs, 32, 127, {ascent + descent}, {ascent}}};")
        out.append("")
    out.append("}  // namespace pg::gfx")
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.normpath(OUT))


if __name__ == "__main__":
    main()
